/**
 * A conformance corpus: valid C++ programs, with the output a native compiler
 * produces.
 *
 * This is the objective answer to "does the fast engine behave like a C++ compiler?".
 * Each case is a complete program a person would actually write, `expect` is its exact
 * stdout, and `support` is honest about which engine is expected to run it:
 *
 * - `fast` - the fast engine must produce exactly that output. These are the regression
 *   guard: every one of them passed when it was added.
 * - `clang-only` - a known gap. The fast engine may refuse it; what it must never do is
 *   print something *else*. A case here that starts passing is a gap closed, and
 *   promoting it to `fast` is the edit that records it.
 *
 * The `note` on a gap says what is missing, so the list doubles as the work plan.
 */

export type Support = 'fast' | 'clang-only';

export interface ConformanceCase {
  readonly name: string;
  readonly file: string;
  readonly code: string;
  /** Exact expected stdout, as clang-wasm produces it. */
  readonly expect: string;
  readonly support: Support;
  /** For a gap: what the fast engine does not do yet. */
  readonly note?: string;
}

